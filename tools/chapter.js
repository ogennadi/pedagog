// Write out the engine as it was at a given chapter:  bun tools/chapter.js 4 > pedagog-ch4.js
//
// pedagog.js is written so that every idea after the first is one block guarded by
// `chapter >= CHAPTER.<name>` (or `<`, `===`). This tool resolves those guards for one chapter
// and drops what comes later, so the result is a complete, runnable engine with no mention of
// ideas it has not had yet -- the file a student would have at the end of that chapter.
// It is textual and relies on the conventions the engine follows: guards on one line, or
// `if (...) {` with the closing brace alone on a line at the same indentation.
import { readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";

const n = parseInt(process.argv[2]);
const src = readFileSync(resolve(dirname(Bun.main), "..", "pedagog.js"), "utf8");
const table = /const CHAPTER = \{([\s\S]*?)\};/.exec(src)[1];
const chapters = Object.fromEntries([...table.matchAll(/(\w+): (\d+)/g)].map((m) => [m[1], parseInt(m[2])]));
const names = Object.entries(chapters).sort((a, b) => a[1] - b[1]).map(([k]) => k);
if (!(n >= 1 && n <= names.length)) { console.error(`usage: bun tools/chapter.js <1..${names.length}>`); process.exit(1); }

// 1. Resolve every guard to a literal.
let text = src.replace(/chapter (>=|<|===) CHAPTER\.(\w+)/g, (_, op, name) => {
  const k = chapters[name];
  return String(op === ">=" ? n >= k : op === "<" ? n < k : n === k);
});
// 2. Fold the literals out of the conditions they sit in.
for (let i = 0; i < 3; i++) {
  text = text
    .replace(/\(true && /g, "(").replace(/ && true\)/g, ")")
    .replace(/\(false \|\| /g, "(").replace(/ \|\| false\)/g, ")")
    .replace(/\([^()]*? \|\| true\)/g, "(true)").replace(/\(true \|\| [^()]*?\)/g, "(true)")
    .replace(/\(false && [^()]*?\)/g, "(false)").replace(/\([^()]*? && false\)/g, "(false)")
    .replace(/\btrue \? ([^:?]+?) : ([^;,)]+)/g, "$1").replace(/\bfalse \? ([^:?]+?) : ([^;,)]+)/g, "$2");
}
// 3. Resolve the ifs: unwrap `if (true)`, drop `if (false)`, line and block forms.
const lines = text.split(/\r?\n/), out = [];
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const m = /^(\s*)if \((true|false)\) (.*)$/.exec(line);
  if (!m) { out.push(line); continue; }
  const [, indent, lit, rest] = m, keep = lit === "true";
  if (rest.endsWith("{")) {                                        // block form, possibly with an else block
    const close = new RegExp(`^${indent}\\}( else \\{)?\\s*$`);
    let j = i + 1; while (j < lines.length && !close.test(lines[j])) j++;
    const body = lines.slice(i + 1, j), hasElse = /else \{/.test(lines[j]);
    let elseBody = [], k = j;
    if (hasElse) { k = j + 1; while (k < lines.length && !new RegExp(`^${indent}\\}\\s*$`).test(lines[k])) k++; elseBody = lines.slice(j + 1, k); }
    for (const b of keep ? body : elseBody) out.push(b.replace(/^  /, ""));
    i = k;
  } else {                                                          // one line: `if (x) stmt;` or `if (x) stmt; else stmt;`
    const parts = rest.split(/; else /);
    let stmt = keep ? parts[0] : parts[1];
    if (stmt) {
      if (/^\{.*\}$/.test(stmt)) stmt = stmt.slice(1, -1).trim();   // `{ a; b; }` on one line
      out.push(indent + stmt.replace(/;?$/, ";"));
    }
  }
}
text = out.join("\n");
// 4. The Chapter option and variable have no meaning in a single chapter's engine.
text = text.split("\n").filter((l) => !/option name Chapter|name === "chapter"|^let chapter = /.test(l)).join("\n");
text = text.replace(/, savedChapter = chapter/, "").replace(/; chapter = LAST_CHAPTER/, "").replace(/; chapter = savedChapter/, "");
text = text.replace(/\bconst LAST_CHAPTER = [^\n]*\n/, "").replace(/\bconst FIXED_DEPTH = [^\n]*\n/, (s) => (n >= chapters.ITERATIVE ? "" : s));
// 5. Trim the chapter table to this chapter and say what the file is.
text = text.replace(/const CHAPTER = \{[\s\S]*?\};/, (block) => block.split("\n").filter((l) => { const m = /(\w+): (\d+)/.exec(l); return !m || parseInt(m[2]) <= n; }).join("\n"));
text = text.replace("================================================================\n                      P E D A G O G",
  `================================================================\n                      P E D A G O G\n        -- chapter ${n} of ${names.length}: ${names[n - 1]} --\n   (generated by tools/chapter.js from pedagog.js; everything the\n   later chapters add has been left out)`);
if (/\bchapter\b/.test(text.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, ""))) console.error("warning: a reference to `chapter` survived");
process.stdout.write(text);
